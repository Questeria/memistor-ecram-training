def e4(ch):
    rs = S.load_phase(REC, "e4")
    if not rs:
        return None
    out = {}
    grid = defaultdict(dict)
    for r in rs:
        key = (r["task"], r["width"], "fp" if r["arm"] == "fp_sgd" else f"{r['spec']['name']}__{r['algo']}")
        grid[key][r["seed"]] = S.metric(r)
    tasks = sorted({k[0] for k in grid})
    rows = []
    for t in tasks:
        widths = sorted({k[1] for k in grid if k[0] == t})
        arms = sorted({k[2] for k in grid if k[0] == t and k[2] != "fp"})
        out[t] = dict(widths=widths, fp={}, arms={}, verdict={})
        for w in widths:
            out[t]["fp"][w] = dict(ci=S.mean_ci(list(grid[(t, w, "fp")].values())), lr=ch["lr"][t][str(w)]["lr"])
            M(f"e4_{t}_fp_w{w}", f(out[t]["fp"][w]["ci"]["mean"], 3 if t == "lm" else 2))
            M(f"e4_{t}_fplr_w{w}", f"{out[t]['fp'][w]['lr']:g}")
        for a in arms:
            out[t]["arms"][a] = {}
            for w in widths:
                if (t, w, a) not in grid:
                    continue
                gaps, _ = S.paired_gaps(t, grid[(t, w, "fp")], grid[(t, w, a)])
                lr = ch.get("devlr", {}).get(t, {}).get(str(w), {}).get(a, {}).get("lr")
                out[t]["arms"][a][w] = dict(gap=S.mean_ci(gaps), lr=lr)
            if len(out[t]["arms"][a]) >= 3:
                v = S.growth({w: x["gap"] for w, x in out[t]["arms"][a].items()})
                out[t]["verdict"][a] = v
                M(f"e4_{t}_{a}_verdict", v)
            for w, x in out[t]["arms"][a].items():
                M(f"e4_{t}_{a}_w{w}_gap", f(x["gap"]["mean"]))
        for w in widths:
            cells = [f"{f(out[t]['fp'][w]['ci']['mean'], 3 if t == 'lm' else 2)} ({out[t]['fp'][w]['lr']:g})"]
            for a in arms:
                x = out[t]["arms"][a].get(w)
                cells.append("--" if x is None else f"{fci(x['gap'])} ({x['lr']:g})" if x["lr"] else fci(x["gap"]))
            rows.append(f"{'CIFAR' if t == 'cifar' else 'LM'} & {w} & " + " & ".join(cells) + "\\\\")
        rows.append(f"\\multicolumn{{3}}{{r}}{{verdict:}} & " + " & ".join(out[t]["verdict"].get(a, "--") for a in arms) + "\\\\\\midrule")
    rows[-1] = rows[-1].replace("\\midrule", "")
    arms_all = sorted({k[2] for k in grid if k[2] != "fp"})
    head = " & ".join(DEV_LABEL[a.split("__")[0]].split(" (")[0] + " " + ALGO_LABEL[a.split("__")[1]] for a in arms_all)
    write_table("scale", "\\begin{table*}[t]\\centering\\footnotesize\\caption{Scale (E4): every arm uses its own "
                "validation-chosen learning rate (in parentheses) at every width; gap (pp for CIFAR, \\% for the LM), mean "
                "and 95\\% interval over 3 seeds paired with FP at its own learning rate. Verdict by the pre-registered rule "
                "(Section~\\ref{sec:scale}).}\\label{tab:scale}\n\\begin{tabular}{ll" + "c" * (1 + len(arms_all)) +
                "}\\toprule Task & Width & FP metric (lr) & " + head + "\\\\\\midrule\n" + "\n".join(rows) +
                "\n\\bottomrule\\end{tabular}\\end{table*}\n")
    rat = [x["lr"] / out[t]["fp"][w]["lr"] for t in tasks for a in out[t]["arms"] for w, x in out[t]["arms"][a].items() if x["lr"]]
    if rat:
        M("e4_lr_ratio_max", f"{max(rat):.0f}"); M("e4_lr_ratio_min", f"{min(rat):g}")
    v = [out[t]["verdict"].get(f"{d}__ttv2") for t in ("cifar", "lm") for d in ("protonic_onen2022", "ecram_li_tang2018") if t in out]
    confirmed = len(v) == 4 and all(x == "GROWS" for x in v)
    out["lane_me_growth_confirmed"] = confirmed
    M("e4_confirmed", "confirmed" if confirmed else "not confirmed")
    cnt = defaultdict(int)
    for t in out:
        if isinstance(out[t], dict) and "verdict" in out[t]:
            for x in out[t]["verdict"].values():
                cnt[x] += 1
