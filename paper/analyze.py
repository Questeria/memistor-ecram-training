def e3():
    rs = S.load_phase(REC, "e3")
    if not rs:
        return None
    out = {}
    grid = defaultdict(list)
    for r in rs:
        dev = r["spec"]["name"] if r["arm"] == "device" else r["arm"]
        grid[(r["task"], dev, r["algo"] if r["arm"] == "device" else "-")].append(r)
    for task in ("mnist", "cifar", "lm"):
        fp = by_seed(grid.get((task, "fp_sgd", "-"), []))
        if not fp:
            continue
        out[task] = dict(fp=S.mean_ci(list(fp.values())), cells={})
        M(f"e3_{task}_fp", f(out[task]["fp"]["mean"], 3 if task == "lm" else 2))
        M(f"e3_{task}_fp_sd", f(out[task]["fp"]["sd"], 3 if task == "lm" else 2))
        if task == "lm" and grid.get((task, "fp_adam", "-")):
            ad = by_seed(grid[(task, "fp_adam", "-")])
            out[task]["adam"] = S.mean_ci(list(ad.values()))
            M("e3_lm_adam", f(out[task]["adam"]["mean"], 3))
            sg = [100 * (fp[s] / ad[s] - 1) for s in sorted(set(fp) & set(ad))]
            out[task]["fp_vs_adam_pct"] = S.mean_ci(sg)
            M("e3_lm_fpvsadam", f(out[task]["fp_vs_adam_pct"]["mean"], 1))
        for d in MAIN_DEVICES:
            for al in ALGOS:
                dv = by_seed(grid.get((task, d, al), []))
                if not dv:
                    continue
                gaps, seeds = S.paired_gaps(task, fp, dv)
                ci = S.mean_ci(gaps)
                lab = S.label(task, ci)
                cell = dict(metric=S.mean_ci(list(dv.values())), gap=ci, label=lab, seeds=seeds)
                if task == "lm" and "adam" in out[task]:
                    ad = by_seed(grid[(task, "fp_adam", "-")])
                    cell["vs_adam_pct"] = S.mean_ci([100 * (dv[s] / ad[s] - 1) for s in seeds if s in ad and math.isfinite(dv[s])])
                out[task]["cells"][f"{d}__{al}"] = cell
                M(f"e3_{task}_{d}_{al}_gap", f(ci["mean"], 2))
                if ci.get("lo") is not None and ci["mean"] != math.inf:
                    M(f"e3_{task}_{d}_{al}_lo", f(ci["lo"], 2)); M(f"e3_{task}_{d}_{al}_hi", f(ci["hi"], 2))
                M(f"e3_{task}_{d}_{al}_label", lab)
    # the table: one row per device x algorithm, one column per task
    rows = []
    for d in MAIN_DEVICES:
        for i, al in enumerate(ALGOS):
            cells = []
            for task in ("mnist", "cifar", "lm"):
                c = out.get(task, {}).get("cells", {}).get(f"{d}__{al}")
                cells.append("not run" if c is None else f"{fci(c['gap'])} {short(c['label'])}")
            rows.append(f"{DEV_LABEL[d] if i == 0 else ''} & {ALGO_LABEL[al]} & " + " & ".join(cells) + "\\\\")
        rows.append("\\midrule")
    rows = rows[:-1]
    fpline = " & ".join(fci(out[t]["fp"], 3 if t == "lm" else 2) if t in out else "--" for t in ("mnist", "cifar", "lm"))
    body = ("\\begin{table*}[t]\\centering\\footnotesize\n\\caption{Main result (E3): gap to the exact-update baseline, mean "
            "and 95\\% t-interval over 5 seeds, paired by seed. MNIST and CIFAR in percentage points of test accuracy; LM in "
            "\\% of bits per byte. P = the whole interval is below the line (2 pp; 5\\%), F = wholly above, U = the interval "
            "contains the line. Every arm uses the FP validation learning rate.}\\label{tab:main}\n"
            "\\begin{tabular}{llccc}\\toprule\nDevice & Algorithm & MNIST gap (pp) & CIFAR-10 subset gap (pp) & "
            "char-LM gap (\\%)\\\\\\midrule\n"
            f"\\multicolumn{{2}}{{l}}{{FP baseline (acc.\\ \\%; bpb)}} & {fpline}\\\\\\midrule\n" + "\n".join(rows) +
            "\n\\bottomrule\\end{tabular}\\end{table*}\n")
    write_table("main", body)
    # summary macros: best tolerant cell per task among published ECRAM devices
    for task in out:
        best = None
        for d in MAIN_DEVICES[:4]:
            for al in ALGOS[1:]:
                c = out[task]["cells"].get(f"{d}__{al}")
                if c and c["gap"]["mean"] is not None and (best is None or c["gap"]["mean"] < best[2]["gap"]["mean"]):
                    best = (d, al, c)
        if best:
            out[task]["best_tolerant"] = dict(device=best[0], algo=best[1], gap=best[2]["gap"], label=best[2]["label"])
            M(f"e3_{task}_best_dev", DEV_LABEL[best[0]]); M(f"e3_{task}_best_algo", ALGO_LABEL[best[1]])
            M(f"e3_{task}_best_gap", f(best[2]["gap"]["mean"])); M(f"e3_{task}_best_label", best[2]["label"])
            if best[2]["gap"].get("lo") is not None:
                M(f"e3_{task}_best_lo", f(best[2]["gap"]["lo"])); M(f"e3_{task}_best_hi", f(best[2]["gap"]["hi"]))
        sgd_fail = [d for d in MAIN_DEVICES[:4] if out[task]["cells"].get(f"{d}__sgd", {}).get("label", "").startswith("FAIL")]
        M(f"e3_{task}_sgd_nfail", str(len(sgd_fail)))
    passing = [d for d in MAIN_DEVICES[:4] if all(any(out.get(t, {}).get("cells", {}).get(f"{d}__{al}", {}).get("label") == "PASS"
                                                       for al in ALGOS) for t in ("mnist", "cifar", "lm"))]
    out["devices_passing_all_three"] = passing
    M("e3_npassall", str(len(passing)))
    M("e3_passall_list", " and ".join(DEV_LABEL[d] for d in passing) if passing else "none")
    # the stricter reading: ONE algorithm on all three tasks
    same = {}
    for d in MAIN_DEVICES:
        for al in ALGOS:
            labs = [out.get(t, {}).get("cells", {}).get(f"{d}__{al}", {}).get("label") for t in ("mnist", "cifar", "lm")]
            same[f"{d}__{al}"] = labs
    allpass = [k for k, v in same.items() if all(x == "PASS" for x in v)]
    nofail = [k for k, v in same.items() if all(x in ("PASS", "UNRESOLVED") for x in v)]
    out["same_algo_all_pass"], out["same_algo_no_fail"] = allpass, nofail
    lab = lambda k: f"{DEV_LABEL[k.split('__')[0]]} with {ALGO_LABEL[k.split('__')[1]]}"
    M("e3_same_npass", str(len(allpass)))
    M("e3_same_nofail_list", "; ".join(lab(k) for k in nofail) if nofail else "none")
    M("e3_same_nnofail", str(len(nofail)))
    return out


