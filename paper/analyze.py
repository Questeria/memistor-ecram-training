def e1():
    rs = S.load_phase(REC, "e1")
    if not rs:
        return None
    arms = defaultdict(list)
    for r in rs:
        key = ("fp" if r["arm"] == "fp_sgd" else r["algo"]) + ("_b64" if r["_name"].endswith("b64") else "")
        arms[key].append(100.0 - S.metric(r))  # test error, %
    res = {k: S.mean_ci(v) for k, v in arms.items()}
    fp, sgd, v1 = (res.get(k, S.mean_ci([])) for k in ("fp", "sgd", "ttv1"))
    verdict = "INCOMPLETE"
    if fp["mean"] is not None and sgd["mean"] is not None and v1["mean"] is not None:
        quant = 1.5 <= fp["mean"] <= 2.5 and 10 <= sgd["mean"] <= 20 and v1["mean"] <= fp["mean"] + 0.5
        qual = sgd["mean"] >= fp["mean"] + 5 and v1["mean"] <= fp["mean"] + 1
        verdict = "QUANTITATIVE" if quant else ("QUALITATIVE" if qual else "NOT REPRODUCED")
    M("e1_verdict", verdict.lower())
    pub = {"fp": "2.0", "sgd": "about 15", "ttv1": "close to 2", "ttv2": "--"}
    rows = []
    for k, lab in (("fp", "FP (exact update)"), ("sgd", "SGD on the RPU-baseline device"), ("ttv1", "Tiki-Taka (TTv1)"),
                   ("ttv2", "TTv2 (ours, 16 columns per batch)")):
        ci = res.get(k, S.mean_ci([]))
        b64 = res.get(k + "_b64", S.mean_ci([]))
        M(f"e1_{k}_err", f(ci["mean"]))
        if ci["mean"] is not None and ci["lo"] is not None:
            M(f"e1_{k}_lo", f(ci["lo"])); M(f"e1_{k}_hi", f(ci["hi"]))
        rows.append(f"{lab} & {pub[k]} & {fci(ci)} & {fci(b64)}\\\\")
    write_table("e1", "\\begin{table}[t]\\centering\\small\\caption{Validation against Gokmen and Haensch 2020 "
                "(FCN 784-256-128-10, MNIST, 50 epochs): test error in \\%, our mean and 95\\% interval over 3 seeds at "
                "batch 16, and one seed at batch 64.}\\label{tab:e1}\n\\begin{tabular}{lccc}\\toprule\n"
                "Arm & Published~\\cite{gokmen2020} & Ours (batch 16) & Ours (batch 64)\\\\\\midrule\n" + "\n".join(rows) +
                "\n\\bottomrule\\end{tabular}\\end{table}\n")
    return dict(arms=res, verdict=verdict)


def e1b():
    rs = S.load_phase(REC, "e1b")
    if not rs:
        return None
    cells = defaultdict(list)
    for r in rs:
        sr = r["spec"].get("ref_err", 0.0) if r["arm"] == "device" else None
        key = (r["algo"] if r["arm"] == "device" else "fp", sr)
        cells[key].append(100.0 - S.metric(r))
    res = {f"{k[0]}|{k[1]}": S.mean_ci(v) for k, v in cells.items()}
    g = lambda a, s: res.get(f"{a}|{s}", S.mean_ci([]))["mean"]
    verdict = "INCOMPLETE"
    if None not in (g("ttv2", 0.5), g("agad", 0.5), g("agad", 0.0), g("cttv2", 0.5)):
        ok = (g("ttv2", 0.5) - g("agad", 0.5) >= 2 and abs(g("agad", 0.5) - g("agad", 0.0)) <= 1
              and g("cttv2", 0.5) <= g("ttv2", 0.5))
        verdict = "REPRODUCED" if ok else "NOT REPRODUCED"
    M("e1b_verdict", verdict.lower())
    rows = []
    for sr in (0.0, 0.5):
        cellsx = [fci(res.get(f"{a}|{sr}", S.mean_ci([]))) for a in ("ttv2", "cttv2", "agad")]
        for a in ("ttv2", "cttv2", "agad"):
            M(f"e1b_{a}_sr{int(sr * 10)}", f(g(a, sr)))
        rows.append(f"$\\sigma_r={sr:g}$ & " + " & ".join(cellsx) + "\\\\")
    fp = res.get("fp|None", S.mean_ci([]))
    M("e1b_fp", f(fp["mean"]))
    write_table("e1b", "\\begin{table}[t]\\centering\\small\\caption{Qualitative check of Rasch et al.\\ 2024 (Fig.~5): a "
                "20-state soft-bounds device with an uncorrected reference offset $\\sigma_r$; test error in \\% (mean and "
                f"range over 2 seeds as a t-interval; 10 epochs). FP: {fci(fp)}.}}\\label{{tab:e1b}}\n"
                "\\begin{tabular}{lccc}\\toprule Offset & TTv2 & c-TTv2 & AGAD\\\\\\midrule\n" + "\n".join(rows) +
                "\n\\bottomrule\\end{tabular}\\end{table}\n")
    return dict(cells=res, verdict=verdict)


