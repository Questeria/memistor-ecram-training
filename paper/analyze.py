def fmt_axis(ax, v):
    if v is None:
        return "--"
    if ax == "tau_steps":
        return "none" if v == math.inf else f"{v:.0e}".replace("e+0", "e")
    if ax == "n_states":
        return f"{v:.0f}"
    return f"{v:.3g}"


def e5(ch):
    rs = S.load_phase(REC, "e5")
    e4r = S.load_phase(REC, "e4")
    if not rs or not e4r:
        return None
    sa = ch["s_algo"]
    base = S.jload(REC / "CATALOG.json")["entries"]["protonic_onen2022"]["spec"]
    fp = defaultdict(list)
    for r in e4r:
        if r["arm"] == "fp_sgd":
            fp[(r["task"], r["width"])].append(S.metric(r))
    out = {}
    for algo in sorted({r["algo"] for r in rs}):
        for (t, w) in sorted({(r["task"], r["width"]) for r in rs if r["algo"] == algo}):
            if (t, w) not in fp:
                continue
            fpm = sum(fp[(t, w)]) / len(fp[(t, w)])
            pts = {ax: defaultdict(list) for ax in S.AXES}
            for r in rs:
                if r["task"] != t or r["width"] != w or r["algo"] != algo:
                    continue
                g = S.gap_value(t, fpm, S.metric(r))
                ax = S.oat_point_axis(r["spec"], base)
                for a_ in (list(S.AXES) if ax is None else [ax]):
                    pts[a_][S.axis_value(r["spec"], a_)].append(g)
            means = {ax: {v: sum(g) / len(g) for v, g in d.items()} for ax, d in pts.items()}
            th = S.thresholds(means, S.GAP_LINE[t])
            bg = means["n_states"].get(1000)
            for ax, v, nm in (("gamma", 0, "gammazero"), ("ref_err", 0, "referrzero"), ("ref_err", 0.05, "referrfive"),
                              ("asym", 0.4, "asymfour"), ("tau_steps", 1000.0, "tauthree"), ("c2c", 4, "ctwocfour"),
                              ("n_states", 100, "levelshundred")):
                if v in means[ax]:
                    M(f"oat_{algo}_{t}_w{w}_{nm}", f(means[ax][v], 1))
            th_rel = S.thresholds({ax: {v: g - bg for v, g in d.items()} for ax, d in means.items()}, S.GAP_LINE[t]) \
                if bg is not None else {}
            out[f"{algo}__{t}_w{w}"] = dict(task=t, width=w, algo=algo, fp_mean=fpm, base_gap=bg, thresholds_rel_D1=th_rel,
                                           points={ax: {str(v): g for v, g in d.items()} for ax, d in pts.items()},
                                           means={ax: {str(v): g for v, g in d.items()} for ax, d in means.items()},
                                           thresholds=th)
    joint = S.jload(REC / "E5-JOINT.json") if (REC / "E5-JOINT.json").exists() else {}
    # spec sheet table (S-ALGO)
    rows = []
    for key, x in out.items():
        if x["algo"] != sa:
            continue
        cells = []
        for ax in S.AXES:
            th = x["thresholds"][ax]
            st = th.get("status", "")
            if th.get("threshold") is None:
                cells.append("n/r")
                continue
            sym = {"down": "$\\ge$", "up": "$\\le$"}[S.AXES[ax]["worse"]]
            val = fmt_axis(ax, th["threshold"])
            itp = f" ({fmt_axis(ax, th['interp'])})" if th.get("interp") else ""
            mark = "$^\\dagger$" if st == "needs improvement" else ("$^*$" if st == "passes over the whole grid" else "")
            cells.append(f"{sym} {val}{itp}{mark}")
            M(f"spec_{x['task']}_w{x['width']}_{ax}", f"{sym} {val}")
        j = joint.get(f"{x['task']}_w{x['width']}", {})
        jtxt = "--"
        for rnd in (2, 1):
            if f"joint_r{rnd}_gap" in j:
                ci = j[f"joint_r{rnd}_gap"]
                jtxt = f"r{rnd}: {f(ci['mean'])} {'pass' if j[f'joint_r{rnd}_pass'] else 'fail'}"
                break
        rows.append(f"{'CIFAR' if x['task'] == 'cifar' else 'LM'} {x['width']} & " + " & ".join(cells) + f" & {jtxt}\\\\")
    write_table("spec", "\\begin{table*}[t]\\centering\\footnotesize\\caption{Device specification sheet (E5) for "
                f"{ALGO_LABEL[sa]}: the weakest grid value of each parameter that keeps the gap under the line (2 pp CIFAR; "
                "5\\% LM) with every other parameter at the protonic base (levels 1000, $a$ 0.05, $\\gamma$ 0.2, $c_{2c}$ 0.3, "
                "no drift, $\\sigma_r$ 0.02); in parentheses the interpolated crossing. $^\\dagger$: the base itself fails "
                "and the value shown is the improvement needed; $^*$: passes over the whole grid; n/r: not reachable on the "
                "grid. Last column: the joint specification (every axis at its threshold at once), mean gap over 3 seeds, "
                "round 1 or the tightened round 2.}\\label{tab:spec}\n\\begin{tabular}{lccccccc}\\toprule Size & Levels & "
                "Asym.\\ $a$ & Nonlin.\\ $\\gamma$ & Noise $c_{2c}$ & Retention $\\tau$ & Ref.\\ err.\\ $\\sigma_r$ & Joint "
                "spec\\\\\\midrule\n" + "\n".join(rows) + "\n\\bottomrule\\end{tabular}\\end{table*}\n")
    # D1 (DEVIATIONS-PAPER.md): the descriptive degradation thresholds, relative to the base device's own gap
    rows = []
    for key, x in out.items():
        if not x.get("thresholds_rel_D1"):
            continue
        cells = []
        for ax in S.AXES:
            th = x["thresholds_rel_D1"][ax]
            sym = {"down": "$\\ge$", "up": "$\\le$"}[S.AXES[ax]["worse"]]
            if th.get("threshold") is None:
                cells.append("n/r")
                continue
            val = fmt_axis(ax, th["threshold"])
            itp = f" ({fmt_axis(ax, th['interp'])})" if th.get("interp") else ""
            mark = "$^*$" if th.get("status") == "passes over the whole grid" else ""
            cells.append(f"{sym} {val}{itp}{mark}")
            M(f"specrel_{x['algo']}_{x['task']}_w{x['width']}_{ax}", f"{sym} {val}")
        M(f"specrel_{x['algo']}_{x['task']}_w{x['width']}_basegap", f(x["base_gap"]))
        rows.append(f"{ALGO_LABEL[x['algo']]} & {'CIFAR' if x['task'] == 'cifar' else 'LM'} {x['width']} & {f(x['base_gap'])} & "
                    + " & ".join(cells) + "\\\\")
    write_table("spec_rel", "\\begin{table*}[t]\\centering\\footnotesize\\caption{Degradation thresholds (descriptive, added "
                "after the one-at-a-time data were seen; DEVIATIONS-PAPER.md D1): the weakest grid value of each parameter whose "
                "gap stays within the line (2 pp CIFAR; 5\\% LM) of the protonic base device's own gap (column 3), all other "
                "parameters at the base; interpolated crossing in parentheses; $^*$ the whole grid stays within; n/r the "
                "nearest grid step already leaves the band.}\\label{tab:specrel}\n\\begin{tabular}{llrcccccc}\\toprule "
                "Alg. & Size & Base gap & Levels & Asym.\\ $a$ & Nonlin.\\ $\\gamma$ & Noise $c_{2c}$ & Retention $\\tau$ & "
                "Ref.\\ err.\\ $\\sigma_r$\\\\\\midrule\n" + "\n".join(rows) + "\n\\bottomrule\\end{tabular}\\end{table*}\n")
    return dict(oat=out, joint=joint)


def e5pair(ch, oat):
    rs = S.load_phase(REC, "e5pair")
    if not rs or not oat:
        return None
    base = S.jload(REC / "CATALOG.json")["entries"]["protonic_onen2022"]["spec"]
    out = []
    for r in rs:
        key = f"{r['algo']}__{r['task']}_w{r['width']}"
        if key not in oat["oat"]:
            continue
        x = oat["oat"][key]
        g = S.gap_value(r["task"], x["fp_mean"], S.metric(r))
        moved = [ax for ax in S.AXES if S.axis_value(r["spec"], ax) != S.axis_value(base, ax)]
        if len(moved) != 2:
            continue
        singles = []
        for ax in moved:
            v = str(S.axis_value(r["spec"], ax))
            singles.append(x["means"][ax].get(v))
        if None in singles:
            continue
        bg = x["means"]["n_states"].get(str(1000))
        inter = g - (singles[0] + singles[1] - (bg or 0.0))
        out.append(dict(task=r["task"], axes=moved, values=[S.axis_value(r["spec"], a) for a in moved], gap=g,
                        single=singles, base_gap=bg, interaction=inter))
    by_task = defaultdict(list)
    for o in out:
        by_task[o["task"]].append(o)
    rows = []
    for t, L in by_task.items():
        L2 = [o for o in L if math.isfinite(o["interaction"])]
        if not L2:
            continue
        mean_i = sum(o["interaction"] for o in L2) / len(L2)
        pos = sum(o["interaction"] > S.GAP_LINE[t] / 2 for o in L2)
        M(f"pair_{t}_mean_inter", f(mean_i)); M(f"pair_{t}_n", str(len(L2))); M(f"pair_{t}_nsyn", str(pos))
        top = sorted(L2, key=lambda o: -o["interaction"])[:3]
        for o in top:
            rows.append(f"{'CIFAR' if t == 'cifar' else 'LM'} & {o['axes'][0]}={fmt_axis(o['axes'][0], o['values'][0])}, "
                        f"{o['axes'][1]}={fmt_axis(o['axes'][1], o['values'][1])} & {f(o['gap'])} & "
                        f"{f(o['single'][0])} + {f(o['single'][1])} & {f(o['interaction'])}\\\\".replace("_", "\\_"))
    write_table("pairs", "\\begin{table}[t]\\centering\\footnotesize\\caption{Pairwise sensitivity (E5): the three largest "
                "interactions per task, interaction = gap(a,b) $-$ [gap(a) + gap(b) $-$ gap(base)].}\\label{tab:pairs}\n"
                "\\begin{tabular}{llccc}\\toprule Task & Pair & Gap(a,b) & Singles & Interaction\\\\\\midrule\n" +
                "\n".join(rows) + "\n\\bottomrule\\end{tabular}\\end{table}\n")
    return out


