WORDS = "Zero One Two Three Four Five Six Seven Eight Nine".split()
MAC = {}


def mname(key):
    out = []
    for part in key.replace("-", "_").replace(".", "_").split("_"):
        p = "".join(WORDS[int(c)] if c.isdigit() else c for c in part)
        out.append(p[:1].upper() + p[1:])
    return "R" + "".join(out)


def M(key, val):
    MAC[mname(key)] = val
    return val


def f(x, nd=2):
    if x is None:
        return "--"
    if x == math.inf:
        return "div."
    return f"{x:.{nd}f}"


def fci(ci, nd=2, unit=""):
    if ci["mean"] is None:
        return "not run"
    if ci["mean"] == math.inf:
        return "diverged"
    if ci["lo"] is None:
        return f"{f(ci['mean'], nd)}{unit} (n=1)"
    return f"{f(ci['mean'], nd)}{unit} [{f(ci['lo'], nd)}, {f(ci['hi'], nd)}]"


def short(lab):
    return {"PASS": "P", "FAIL": "F", "UNRESOLVED": "U", "FAIL (diverged)": "F"}.get(lab, lab)


def tesc(s):
    """Escape free text (fault names, descriptions) for LaTeX."""
    for a, b in (("\\", "/"), ("_", "\\_"), ("&", "\\&"), ("%", "\\%"), ("#", "\\#"), ("~", "$\\sim$")):
        s = s.replace(a, b)
    return s


def write_table(name, body):
    (TEX / "tables").mkdir(parents=True, exist_ok=True)
    # every tabular is fitted to the text width (\fitbox: resizebox in the PDF, identity in the HTML)
    body = body.replace("\\begin{tabular}", "\\fitbox{\\begin{tabular}").replace("\\end{tabular}", "\\end{tabular}}")
    (TEX / "tables" / f"{name}.tex").write_bytes(("% generated by analyze.py (do not edit)\n" + body).encode("utf-8"))


def by_seed(rs):
    return {r["seed"]: S.metric(r) for r in rs}


