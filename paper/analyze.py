def checks():
    a = S.jload(REC / "TESTS-PAPER.json")
    b = S.jload(REC / "TESTS-laneME-checks-on-paper-sim.json")
    nc = len(a["checks"]) + len(b["checks"])
    nf = len(a["faults"]) + len(b["faults"])
    ok = a["all_ok"] and b["all_ok"]
    M("nChecks", str(nc)); M("nFaults", str(nf))
    MAC["nChecks"] = str(nc); MAC["nFaults"] = str(nf)
    rows = []
    for src in (b, a):
        for k, v in src["checks"].items():
            caught = [fn for fn, fv in src["faults"].items() if fv["check"] == k and fv["caught"]]
            rows.append(f"\\texttt{{{k.replace('_', chr(92) + '_')}}} & {'pass' if v['passed'] else 'FAIL'} & "
                        f"{tesc('; '.join(caught)) if caught else '--'}\\\\")
    write_table("checks", "\\begin{table}[h]\\centering\\footnotesize\\caption{Simulator checks and the planted faults each "
                "one catches (records/TESTS-PAPER.json, records/TESTS-laneME-checks-on-paper-sim.json).}\\label{tab:checks}\n"
                "\\begin{tabular}{p{0.3\\linewidth}lp{0.55\\linewidth}}\\toprule Check & Result & Planted faults caught\\\\"
                "\\midrule\n" + "\n".join(rows) + "\n\\bottomrule\\end{tabular}\\end{table}\n")
    return dict(n_checks=nc, n_faults=nf, all_ok=ok)


