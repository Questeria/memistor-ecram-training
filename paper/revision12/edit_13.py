"""Version 13 of the memistor paper: the answer to review 10 (Codex's regression review of version 12 and archive v1.2, 2026-10-29).
No experiment and no number changes.  The availability section names archive v1.3, the tenth review and its response; the history
gains version 13 (version 12 is no longer "this paper").  Table 11's caption ("versions 2--11", finding 3) is regenerated by
revision/analyze_rev.py, not here; findings 1, 2 (the archive's README) and 4 (revision9/name_check_v10.py) are outside the paper.

    python -I -B revision12/edit_13.py

Each anchor is matched with any run of whitespace between its words and must occur exactly once (edit_10.py's rule); nothing is
written unless every anchor of every file matched.
"""
import re
from pathlib import Path

TEX = Path(__file__).resolve().parent.parent / "tex"

EDITS = {
    "body.tex": [
        ("archive version",
         r"(this DOI cites all versions; version~1.2 of the archive holds version~12 of this paper, version~1.1 holds version~11, and"
         r" version~1.0 holds version~9)",
         r"(this DOI cites all versions; version~1.3 of the archive holds version~13 of this paper, version~1.2 holds version~12,"
         "\nversion~1.1 holds version~11, and version~1.0 holds version~9)"),
        ("release", r"(release v1.2)", r"(release v1.3)"),
        ("reviews", r"the nine independent reviews", r"the ten independent reviews"),
        ("responses", r"\texttt{RESPONSE-TO-REVIEW-9.md});", r"\texttt{RESPONSE-TO-REVIEW-9.md}, \texttt{RESPONSE-TO-REVIEW-10.md});"),
    ],
    "app_revision.tex": [
        ("v12 not current", r"Version 12 (October 29, 2026; this paper) answers", r"Version 12 (October 29, 2026) answers"),
        ("v13", r"labels its version-1 values as superseded.",
         r"labels its version-1 values as" "\n" r"superseded." "\n"
         r"Version 13 (October 31, 2026; this paper) answers a tenth review, of version 12 and version 1.2 of the archive" "\n"
         r"(\texttt{RESPONSE-TO-REVIEW-10.md}; no experiment was run and no number changed). It found the Welch correction right" "\n"
         r"and four small slips outside the results, all corrected: the archive's README said that no other printed number changed," "\n"
         r"although all eight Welch intervals moved, and counted eight reviews; the caption of Table~\ref{tab:rev_width} dated the" "\n"
         r"rounded degrees of freedom to versions 1 to 11, not 2 to 11 (version 1 used another width test); and a self-test of the" "\n"
         r"name check left a PDF open, so its clean-up failed on Windows."),
    ],
}


def apply(name, subs):
    p = TEX / name
    t = p.read_bytes().decode("utf-8")
    for tag, a, b in subs:
        pat = r"\s+".join(re.escape(w) for w in a.split())
        n = len(re.findall(pat, t))
        assert n == 1, (name, tag, n)
        t = re.sub(pat, lambda m: b, t)
    return p, t


out = [apply(n, s) for n, s in EDITS.items()]        # every anchor of every file first
for p, t in out:
    p.write_bytes(t.encode("utf-8"))
print("edited", ", ".join(p.name for p, _ in out))
