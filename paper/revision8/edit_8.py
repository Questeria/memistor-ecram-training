from pathlib import Path

P = Path(__file__).resolve().parent.parent
V9 = ("Version 9 (October 28, 2026; this paper) corrects the deviation count R1--R6 to R1--R8, found by the deposit's "
      "clean-room regeneration.")


def edit(path, subs):
    t = path.read_bytes().decode("utf-8")
    for name, a, b in subs:
        assert t.count(a) == 1, (path.name, name, t.count(a))
        t = t.replace(a, b)
    assert "\r\n" not in t
    path.write_bytes(t.encode("utf-8"))


